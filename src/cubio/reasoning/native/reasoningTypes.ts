/**
 * CUBiO AI — Funnel 39: Native Information Reasoning Engine
 * Phase 3 — Information Intelligence
 * src/cubio/reasoning/native/reasoningTypes.ts
 *
 * Universal type contracts for native information reasoning.
 * Formulates reasoning in explicit deterministic steps (Premise -> Relation -> Inference),
 * preserves source provenance, explicitly represents missing evidence and contradictions,
 * enforces intermediate state immutability, and guarantees zero memory mutation.
 */

/** Overall outcome status of the reasoning execution */
export type ReasoningStatus =
  | 'PROVED'                  // Query/hypothesis was deductively proven with verified support
  | 'REFUTED'                // Query/hypothesis was disproven or contradictory
  | 'INCONCLUSIVE'           // Insufficient evidence or missing intermediate premises
  | 'CONTRADICTION_DETECTED' // Conflicting premises or inferences detected without silent resolution
  | 'BUDGET_EXCEEDED';       // Terminated gracefully when reasoning depth or time expired

/** Origin classification of an input or intermediate premise */
export type PremiseType =
  | 'OBSERVED_FACT'        // Directly extracted from empirical NativeInformationObject
  | 'DISCOVERED_PATTERN'   // Instantiated from verified DiscoveredPattern
  | 'DERIVED_INFERENCE';   // Synthesized from prior reasoning steps

/**
 * Epistemic confidence status of a premise or inference.
 * HARD RULE: Unsupported conclusions must NEVER be marked as ESTABLISHED_FACT.
 */
export type EpistemicStatus =
  | 'ESTABLISHED_FACT'     // Strictly reserved for 100% verified facts or unviolated invariant deductions
  | 'SUPPORTED_HYPOTHESIS' // Strong deductive or inductive support, but containing empirical variance
  | 'UNSUPPORTED'          // Speculative claim or premise lacking sufficient grounding
  | 'CONTRADICTED';        // Refuted by an explicit contradiction

/** Canonical reasoning rules applicable during inference */
export type ReasoningRuleType =
  | 'DIRECT_ASSERTION'           // Direct assertion of an empirical observation
  | 'TRANSITIVE_CHAIN'           // (A -> B) & (B -> C) => (A -> C)
  | 'PATTERN_INSTANTIATION'      // Applying a discovered relational or structural pattern to concrete facts
  | 'SPATIAL_LATTICE_INFERENCE'  // Composing 3D spatial lattice offset vectors in 7x7x7 lattice
  | 'MODUS_PONENS'               // (P -> Q) & P => Q
  | 'CONTRADICTION_REFUTATION';  // Identifying incompatible mutual claims

/** A structured premise feeding into the reasoning engine */
export interface ReasoningPremise {
  readonly premiseId: string;
  readonly type: PremiseType;
  readonly statement: string;
  readonly subject: string;
  readonly predicate: string;
  readonly object: string | number | boolean | readonly number[];
  readonly confidence: number;
  readonly epistemicStatus: EpistemicStatus;
  readonly sourceObjectId?: string;
  readonly sourceStorageKey?: string;
  readonly sourcePatternId?: string;
  readonly timestamp: number;
}

/** Formal relation or inference rule applied to premises */
export interface ReasoningRelation {
  readonly ruleType: ReasoningRuleType;
  readonly name: string;
  readonly description: string;
  readonly confidenceMultiplier: number;
}

/** Formally derived inference generated by a reasoning step */
export interface ReasoningInference {
  readonly inferenceId: string;
  readonly stepNumber: number;
  readonly statement: string;
  readonly subject: string;
  readonly predicate: string;
  readonly object: string | number | boolean | readonly number[];
  readonly confidence: number;
  readonly epistemicStatus: EpistemicStatus;
  readonly ruleApplied: ReasoningRuleType;
  readonly ruleType?: ReasoningRuleType;
  readonly supportedByPremiseIds: readonly string[];
  readonly sourceObjectIds: readonly string[];
  readonly sourcePatternIds: readonly string[];
  readonly parentStepNumbers: readonly number[];
  readonly isSupported: boolean;
}

/** Explicitly surfaced contradiction between two premises or inferences */
export interface ReasoningContradiction {
  readonly contradictionId: string;
  readonly premiseAId: string;
  readonly premiseBId: string;
  readonly subject: string;
  readonly predicate: string;
  readonly claimA: string | number | boolean | readonly number[];
  readonly claimB: string | number | boolean | readonly number[];
  readonly description: string;
  readonly reason?: string;
  readonly detectedAtStep: number;
}

/** Explicitly surfaced gap where evidence is required but missing */
export interface MissingEvidence {
  readonly missingEvidenceId: string;
  readonly targetConclusion: string;
  readonly subject?: string;
  readonly expectedSubject?: string;
  readonly expectedPredicate: string;
  readonly expectedObject?: string | number | boolean;
  readonly description: string;
  readonly reason?: string;
  readonly impact: string;
}

/** A single, explicit, deterministic reasoning step in the trace */
export interface ReasoningStep {
  readonly stepNumber: number;
  readonly timestamp: number;
  readonly inputPremiseIds: readonly string[];
  readonly relation: ReasoningRelation;
  readonly inference: ReasoningInference;
  readonly stateSnapshotHash: string;
}

/**
 * Immutable snapshot of the reasoning environment at a specific step.
 * Built strictly on reference pointers to prevent in-place mutation.
 */
export interface ReasoningState {
  readonly stateId: string;
  readonly stepNumber: number;
  readonly activePremises: readonly ReasoningPremise[];
  readonly establishedInferences: readonly ReasoningInference[];
  readonly contradictions: readonly ReasoningContradiction[];
  readonly missingEvidence: readonly MissingEvidence[];
  readonly parentStateHash?: string;
  readonly stateHash: string;
}

/** Optional target query, hypothesis, or goal to prove/evaluate */
export interface ReasoningQuery {
  readonly queryId: string;
  readonly targetSubject?: string;
  readonly targetPredicate?: string;
  readonly targetObject?: string | number | boolean;
  readonly hypothesisStatement?: string;
  readonly maxDepth?: number;
  readonly budgetMs?: number;
}

/** Engine execution configuration */
export interface ReasoningConfig {
  readonly maxDepth?: number;          // Maximum deduction depth (default: 6)
  readonly maxSteps?: number;          // Maximum total inference steps (default: 50)
  readonly budgetMs?: number;          // Wall-clock time budget in ms (default: 2000)
  readonly minConfidence?: number;      // Confidence cutoff (default: 0.1)
  readonly allowHypotheses?: boolean;  // Whether to emit non-fact hypotheses (default: true)
  readonly haltOnContradiction?: boolean; // Whether to halt inference when a contradiction is detected (default: true)
}

/** Final comprehensive immutable trace returned by the reasoning engine */
export interface ReasoningTraceResult {
  readonly resultId: string;
  readonly status: ReasoningStatus;
  readonly query?: ReasoningQuery;
  readonly steps: readonly ReasoningStep[];
  readonly finalInferences: readonly ReasoningInference[];
  readonly contradictions: readonly ReasoningContradiction[];
  readonly missingEvidence: readonly MissingEvidence[];
  readonly states: readonly ReasoningState[];
  readonly totalStepsExecuted: number;
  readonly executionDurationMs: number;
  readonly budgetExceeded: boolean;
  readonly inputChecksum: string;
  readonly resultChecksum: string;
  readonly timestamp: number;
}
